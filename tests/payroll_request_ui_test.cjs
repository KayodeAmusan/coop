const fs = require('fs');
const vm = require('vm');
const assert = require('assert');
const source = fs.readFileSync(require('path').join(__dirname, '..', 'payprocess.php'), 'utf8');
const start = source.indexOf('class PayrollProcessor {');
const end = source.indexOf('// Initialize when document is ready', start);
let request;
const context = { $: { ajax: options => { request = options; } } };
vm.createContext(context);
vm.runInContext(source.slice(start, end) + '\nthis.PayrollProcessor = PayrollProcessor;', context);
const payroll = Object.create(context.PayrollProcessor.prototype);
Object.assign(payroll, { currentPeriod: 3, endPeriod: 4, totalPeriods: 2, processedPeriods: 0, memberId: 'COOP-001 & literal', allResults: [], updateProgress() {}, processNextPeriod() {}, handleProgress() {} });
context.PayrollProcessor.prototype.processNextPeriod.call(payroll);
assert.strictEqual(request.type, 'POST');
assert.strictEqual(request.url, 'classes/process.php');
assert.strictEqual(request.data.PeriodID, 3);
assert.strictEqual(request.data.member_id, 'COOP-001 & literal');
assert(!request.url.includes('?'));
request.success('PROGRESS_DATA: Starting processing...');
assert.strictEqual(payroll.allResults[0].success, false);
request.success('COMPLETION: SUCCESS\n');
assert.strictEqual(payroll.allResults[1].success, true);
request.success('ERROR: failure\nCOMPLETION: SUCCESS\n');
assert.strictEqual(payroll.allResults[2].success, false);
request.error({}, 'error', 'Forbidden');
assert.strictEqual(payroll.allResults[3].success, false);
console.log('PASS payroll actual AJAX uses POST body, retains literal member ID, and requires explicit server completion');
